// ClassIds.h
// -----------------------------------------------------------------------------
// Engine-agnostic identifiers for the four playable classes and their
// resource models. Used by aspect class restrictions and by the UE class
// data assets (UEclipseClassDefinition) which hold the presentation/ability data.
// -----------------------------------------------------------------------------
#pragma once

#include "EclipseCore/EclipseCoreTypes.h"

namespace Eclipse
{
	enum class EClassId : u8
	{
		ArchitectOfFlesh,  // Biomass / Blood Energy
		ChronoSovereign,   // Temporal Strain
		SpireWarden,       // Seismic Pressure
		EclipsePuppeteer,  // Puppet Strings / Lunar Essence
		Count
	};

	/** How a class resource behaves over time. */
	enum class EResourceModel : u8
	{
		Builder,  // Starts empty, generated by actions, decays out of combat (Biomass, Seismic Pressure).
		Spender,  // Starts full, regenerates over time (Lunar Essence).
		Strain    // Starts empty, abilities ADD strain; overflowing max causes a penalty (Temporal Strain).
	};

	struct ResourceRules
	{
		EResourceModel Model = EResourceModel::Builder;
		float Max = 100.f;
		float RegenPerSecond = 0.f;
		float OutOfCombatDecayPerSecond = 0.f;
	};

	constexpr ResourceRules GetDefaultResourceRules(EClassId Class)
	{
		switch (Class)
		{
		case EClassId::ArchitectOfFlesh: return { EResourceModel::Builder, 150.f, 0.f, 6.f };
		case EClassId::ChronoSovereign:  return { EResourceModel::Strain, 100.f, -12.f, 0.f }; // Strain bleeds off.
		case EClassId::SpireWarden:      return { EResourceModel::Builder, 100.f, 0.f, 10.f };
		case EClassId::EclipsePuppeteer: return { EResourceModel::Spender, 120.f, 8.f, 0.f };
		default:                         return {};
		}
	}
}
